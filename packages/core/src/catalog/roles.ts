/** Every title once, with the families it belongs to (a title can sit in several). */
export function allTitles(): { title: string; families: string[] }[] {
  const map = new Map<string, string[]>();
  for (const f of ROLE_FAMILIES) {
    for (const t of f.titles) map.set(t, [...(map.get(t) ?? []), f.label]);
  }
  return [...map].map(([title, families]) => ({ title, families })).sort((a, b) => a.title.localeCompare(b.title));
}
